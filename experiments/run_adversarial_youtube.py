#!/usr/bin/env python3
"""Task 6: clean vs adversarial-retrained classifier on the real YouTube subset.

Scores the YouTube scam-baiter corpus (``data/external/youtube_baiters``) with
both the deployed call classifier (``models/call_fraud_xgb.json``) and the
adversarial-retrained variant (``models/call_fraud_xgb_adversarial.json``), each
paired with its own TF-IDF vectoriser.  Reports headline metrics for both heads
and the F1 delta, so the paper can state whether adversarial retraining helps,
hurts, or is neutral on held-out real audio (transcribed via Whisper).

This is an evaluation-only harness: it reads existing model artifacts and the
annotated YouTube split.  It does not retrain anything.

Usage::

    python experiments/run_adversarial_youtube.py
    python experiments/run_adversarial_youtube.py --threshold 0.5
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

_PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(_PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(_PROJECT_ROOT))

from experiments.dataset_loader import load_youtube_baiters  # noqa: E402
from experiments.run_adversarial import (  # noqa: E402
    _CLASSIFIER_PATHS, _metrics, _scores,
)
from sentinel_edge.classifier.xgb_classifier import FraudClassifier  # noqa: E402
from sentinel_edge.features.feature_pipeline import FeaturePipeline  # noqa: E402

_HEADS = [
    ("default", "Clean (call_fraud_xgb)"),
    ("adv_retrained", "Adversarial-retrained"),
]


def _record_text(rec) -> str:
    """Return the full transcript text for a CallRecord."""
    txt = getattr(rec, "transcript", None)
    if txt:
        return str(txt)
    sentences = getattr(rec, "sentences", None) or []
    return " ".join(str(s) for s in sentences)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--threshold", type=float, default=0.5)
    ap.add_argument(
        "--out",
        default=str(_PROJECT_ROOT / "results" / "adversarial_youtube.json"),
    )
    ap.add_argument(
        "--tex",
        default=str(_PROJECT_ROOT / "paper" / "_adv_youtube.tex"),
    )
    args = ap.parse_args()

    recs = load_youtube_baiters()
    texts = [_record_text(r) for r in recs]
    y = np.array([int(getattr(r, "label", 0)) for r in recs], dtype=int)
    n, n_pos = int(len(y)), int(np.sum(y == 1))
    print(f"[load] youtube_baiters: n={n}  pos={n_pos}  neg={n - n_pos}")

    results: dict = {
        "dataset": "youtube_baiters",
        "n": n,
        "n_pos": n_pos,
        "n_neg": n - n_pos,
        "threshold": args.threshold,
        "heads": {},
    }

    print(f"\n## Adversarial retraining on real YouTube audio "
          f"(n={n}, threshold={args.threshold})")
    print("| Head | F1 | Precision | Recall | AUROC |")
    print("|---|---|---|---|---|")

    for key, label in _HEADS:
        model_p, tfidf_p = _CLASSIFIER_PATHS[key]
        if not model_p.exists() or not tfidf_p.exists():
            print(f"  [skip] {key}: artifacts not found")
            continue
        pipe = FeaturePipeline(str(tfidf_p))
        clf = FraudClassifier(str(model_p))
        scores = _scores(texts, pipe, clf)
        m = _metrics(y, scores, thresh=args.threshold)
        results["heads"][key] = m
        print(f"| {label} | {m['f1']:.3f} | {m['precision']:.3f} "
              f"| {m['recall']:.3f} | {m.get('auroc', float('nan')):.3f} |")

    clean = results["heads"].get("default")
    adv = results["heads"].get("adv_retrained")
    if clean and adv:
        delta = adv["f1"] - clean["f1"]
        results["delta_f1"] = float(delta)
        print(f"\nF1 delta (adversarial - clean): {delta:+.3f}")

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(results, indent=2))
    print(f"\nwrote {out_path}")

    # ---- LaTeX macros (digit-free command names) -----------------------
    def _pct(x: float) -> str:
        return f"{x:.3f}"

    lines = [
        "% Auto-generated by experiments/run_adversarial_youtube.py",
        f"\\newcommand{{\\AdvYtN}}{{{n}}}",
        f"\\newcommand{{\\AdvYtNPos}}{{{n_pos}}}",
        f"\\newcommand{{\\AdvYtNNeg}}{{{n - n_pos}}}",
    ]
    if clean:
        lines += [
            f"\\newcommand{{\\AdvYtCleanFOne}}{{{_pct(clean['f1'])}}}",
            f"\\newcommand{{\\AdvYtCleanPrec}}{{{_pct(clean['precision'])}}}",
            f"\\newcommand{{\\AdvYtCleanRec}}{{{_pct(clean['recall'])}}}",
            f"\\newcommand{{\\AdvYtCleanAuroc}}"
            f"{{{_pct(clean.get('auroc', float('nan')))}}}",
        ]
    if adv:
        lines += [
            f"\\newcommand{{\\AdvYtAdvFOne}}{{{_pct(adv['f1'])}}}",
            f"\\newcommand{{\\AdvYtAdvPrec}}{{{_pct(adv['precision'])}}}",
            f"\\newcommand{{\\AdvYtAdvRec}}{{{_pct(adv['recall'])}}}",
            f"\\newcommand{{\\AdvYtAdvAuroc}}"
            f"{{{_pct(adv.get('auroc', float('nan')))}}}",
        ]
    if clean and adv:
        lines.append(
            f"\\newcommand{{\\AdvYtDeltaFOne}}"
            f"{{{results['delta_f1']:+.3f}}}"
        )
    tex_path = Path(args.tex)
    tex_path.write_text("\n".join(lines) + "\n")
    print(f"wrote {tex_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
